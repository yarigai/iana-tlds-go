// Command updatetlds fetches the current TLD list from IANA and writes
// tlds_data.go in the current directory (the module root).
//
// Exits early (unchanged) if the list of TLDs hasn't changed, even when IANA's
// Last-Updated timestamp has.
// Run with: go generate ./...  (or: go run ./internal/updatetlds)
package main

import (
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strings"
	"time"
)

const (
	ianaURL = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt"
	outFile = "tlds_data.go"
)

var (
	headerRe = regexp.MustCompile(`Last Updated (.+UTC)`)
	rawRe    = regexp.MustCompile(`(?m)^const rawTLDs = "([^"]*)"`)
)

func main() {
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Get(ianaURL)
	if err != nil {
		log.Fatalf("Failed to fetch IANA TLD list: %v", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("Failed to fetch IANA TLD list: HTTP %d", resp.StatusCode)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}

	lines := strings.Split(string(body), "\n")
	lastUpdated := time.Now().UTC()
	if m := headerRe.FindStringSubmatch(lines[0]); m != nil {
		// IANA header looks like "Tue Oct  6 07:07:01 2026 UTC".
		if t, err := time.Parse("Mon Jan _2 15:04:05 2006 MST", m[1]); err == nil {
			lastUpdated = t.UTC()
		}
	}
	// Same format as JS Date#toISOString so both ports ship identical values.
	lastUpdatedISO := lastUpdated.Format("2006-01-02T15:04:05.000Z")

	var tlds []string
	for _, line := range lines {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if t := strings.ToLower(strings.TrimSpace(line)); t != "" {
			tlds = append(tlds, t)
		}
	}
	joined := strings.Join(tlds, " ")

	// Exit early if the TLD list itself hasn't changed. IANA bumps its
	// Last-Updated timestamp almost daily even when the list is identical.
	if existing, err := os.ReadFile(outFile); err == nil {
		if m := rawRe.FindSubmatch(existing); m != nil && string(m[1]) == joined {
			fmt.Printf("TLD list unchanged (%d TLDs, IANA %s).\n", len(tlds), lastUpdatedISO)
			return
		}
	}

	content := "// Code generated by go run ./internal/updatetlds; DO NOT EDIT.\n\n" +
		"package ianatlds\n\n" +
		"// LastUpdated is the ISO 8601 timestamp of the IANA source file bundled in this release.\n" +
		fmt.Sprintf("const LastUpdated = %q\n\n", lastUpdatedISO) +
		// ponytail: one space-separated string keeps the generated file small; split once at init.
		fmt.Sprintf("const rawTLDs = %q\n", joined)

	if err := os.WriteFile(outFile, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("Updated: %d TLDs, last updated %s\n", len(tlds), lastUpdatedISO)
}
